package org.supply.app;

import com.typesafe.config.Config;
import com.typesafe.config.ConfigFactory;
import com.typesafe.config.ConfigParseOptions;
import com.typesafe.config.ConfigRenderOptions;
import org.supply.loader.BranchGridGenerator;
import org.supply.loader.ExcelGridReader;
import org.supply.loader.ElectricalObjectExpander;
import org.supply.loader.GridModelLoader;
import org.supply.loader.BranchRouteGenerator;
import java.util.LinkedHashMap;
import java.util.Map;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.io.IOException;

/** Standalone preparation step; generated files remain ordinary, editable grid configurations. */
public final class GridPreprocessor {
    private GridPreprocessor() { }
    public static void main(String[] args) throws IOException {
        if (args.length < 2 || args.length > 3 || (args.length == 3 && !args[2].equals("--overwrite")))
            throw new IllegalArgumentException("Usage: GridPreprocessor <branches.conf|input.xlsx> <grid_generated.conf> [--overwrite]");
        Path input = Path.of(args[0]).toAbsolutePath().normalize();
        Path output = Path.of(args[1]).toAbsolutePath().normalize();
        if (input.equals(output) || (Files.exists(output) && Files.isSameFile(input, output)))
            throw new IllegalArgumentException("Input and output must be different files");
        ExcelGridReader.Result excel=input.getFileName().toString().toLowerCase(java.util.Locale.ROOT).endsWith(".xlsx")
                ? ExcelGridReader.read(input) : null;
        Config description = excel==null ? ConfigFactory.parseFile(input.toFile(),
                ConfigParseOptions.defaults().setAllowMissing(false)).resolve() : ConfigFactory.empty();
        if (excel==null && !description.hasPath("dcsim.grid")) throw new IllegalArgumentException("Missing dcsim.grid");
        Config grid = excel==null ? BranchGridGenerator.generate(description.getConfig("dcsim.grid")) : excel.grid();
        // Use the existing compiler to validate the generated object vocabulary before writing.
        if(excel==null) ElectricalObjectExpander.inspect(grid.root().unwrapped()).requireCalculationReady();
        Config outputConfig = ConfigFactory.empty().withValue("dcsim.grid", grid.root());
        String content = "# Generated by GridPreprocessor. This file can be edited and used independently.\n"
                + outputConfig.root().render(ConfigRenderOptions.defaults().setJson(false)
                .setFormatted(true).setComments(false).setOriginComments(false)) + "\n";
        var model = new GridModelLoader().load(ConfigFactory.empty().withValue("grid", grid.root()));
        var reports = excel==null ? SwitchGearConnectionReport.render(model, grid) : ExcelNetworkReport.render(model,excel);
        var routes = excel==null ? BranchRouteGenerator.generate(description.getConfig("dcsim.grid"), model) : excel.routes();
        String filename = output.getFileName().toString();
        String stem = filename.endsWith(".conf") ? filename.substring(0, filename.length() - 5) : filename;
        Path reportDirectory = output.resolveSibling(stem + "_checks");
        Map<Path, String> files = new LinkedHashMap<>();
        files.put(output, content);
        Path routesOutput = null;
        if (!routes.isEmpty()) {
            String routeStem = stem.endsWith("_grid_generated")
                    ? stem.substring(0, stem.length() - "_grid_generated".length()) + "_routes_generated"
                    : stem + "_routes";
            routesOutput = output.resolveSibling(routeStem + ".conf");
            Config routeConfig = ConfigFactory.empty().withValue("dcsim.traffic.routes", com.typesafe.config.ConfigValueFactory.fromMap(routes));
            if (excel != null) {
                var views = routes.keySet().stream().map(id -> Map.of("route_id", id, "sheet", id)).toList();
                routeConfig = routeConfig.withValue("dcsim.track.route_views", com.typesafe.config.ConfigValueFactory.fromIterable(views))
                        .withValue("dcsim.track.junctions", com.typesafe.config.ConfigValueFactory.fromIterable(excel.trackJunctions()));
            }
            files.put(routesOutput, "# Generated electrical routes; timetable and templates are defined separately.\n"
                    + routeConfig.root().render(ConfigRenderOptions.defaults().setJson(false)
                    .setFormatted(true).setComments(false).setOriginComments(false)) + "\n");
        }
        reports.forEach((name, report) -> files.put(reportDirectory.resolve(name), report));
        // Detect ordinary collisions before changing any output in this generation.
        // CREATE_NEW still protects against concurrent creators when overwrite is not requested.
        for (Path file : files.keySet()) {
            if (file.equals(input) || (Files.exists(file) && Files.isSameFile(file, input)))
                throw new IllegalArgumentException("Output/report must not replace the input: " + file);
            for (Path parent = file.getParent(); parent != null; parent = parent.getParent()) {
                if (Files.exists(parent) && !Files.isDirectory(parent))
                    throw new NotDirectoryException(parent.toString());
            }
            if (Files.isDirectory(file) || (Files.exists(file) && args.length != 3))
                throw new FileAlreadyExistsException(file.toString());
        }
        for (var file : files.entrySet()) {
            Files.createDirectories(file.getKey().getParent());
            Files.writeString(file.getKey(), file.getValue(), StandardCharsets.UTF_8,
                    StandardOpenOption.WRITE, args.length == 3 ? StandardOpenOption.CREATE : StandardOpenOption.CREATE_NEW,
                    args.length == 3 ? StandardOpenOption.TRUNCATE_EXISTING : StandardOpenOption.WRITE);
        }
        if (routesOutput != null) System.out.println("Generated routes: " + routesOutput + " (" + routes.size() + " routes)");
        if (!reports.isEmpty()) System.out.println("Switchgear reports: " + reportDirectory + " (" + reports.size() + " files)");
        System.out.println("Generated grid: " + output);
        if(excel==null) System.out.println("Objects: " + grid.getConfig("electricalObjects").root().size()
                + "; associations: " + grid.getConfigList("electricalAssociations").size());
        else System.out.print(reports.get("network_summary.txt"));
    }
}
